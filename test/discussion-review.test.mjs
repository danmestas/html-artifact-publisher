import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { startWorker, createArtifact, freePort } from './helpers/worker.mjs';

const work = mkdtempSync(join(tmpdir(), 'hap-discussion-review-'));
let worker;
before(async () => {
  const port = await freePort();
  worker = await startWorker(work, { OWNER_EMAIL: 'owner@example.com', TEST_MAIL_TRANSPORT: 'loopback', APP_ORIGIN: `http://127.0.0.1:${port}` }, { port });
});
after(() => { worker?.stop(); rmSync(work, { recursive: true, force: true }); });
async function request(a, suffix, { method = 'GET', body, cookie = '', token = a.read } = {}) {
  const headers = { Origin: worker.base, ...(token ? { Authorization: `Token ${token}` } : {}) };
  if (cookie) headers.Cookie = cookie;
  const response = await fetch(`${worker.base}/api/artifacts/${a.id}${suffix}`, { method, headers, body: body === undefined ? undefined : JSON.stringify(body) });
  const json = await response.json();
  return { status: response.status, json, cookie: response.headers.getSetCookie().find(s => s.startsWith('hap_guest='))?.split(';')[0] };
}
async function login(email) {
  const response = await fetch(`${worker.base}/api/auth/request`, { method: 'POST', headers: { Origin: worker.base }, body: JSON.stringify({ email }) });
  assert.equal(response.status, 200);
  const challenge = await response.json();
  assert.ok(typeof challenge.loginUrl === 'string', 'loopback login link is available');
  const token = new URL(challenge.loginUrl).hash.slice(7);
  const verified = await fetch(`${worker.base}/api/auth/verify`, { method: 'POST', headers: { Origin: worker.base }, body: JSON.stringify({ token }) });
  assert.equal(verified.status, 200);
  const cookie = verified.headers.getSetCookie().find(c => c.startsWith('artifact_session='))?.split(';')[0];
  assert.ok(cookie, 'verified account has private session cookie');
  return cookie;
}
async function profile(a, name) {
  const r = await request(a, '/guest', { method: 'PUT', body: { name } });
  assert.equal(r.status, 200);
  assert.ok(r.cookie, 'profile created a private cookie');
  return r.cookie;
}

test('thread references survive filtering and pagination', async () => {
  const a = await createArtifact(worker.base, worker.owner, '<h1 id="one">One</h1>');
  const cookie = await profile(a, 'First reader');
  const first = await request(a, '/tickets', { method: 'POST', cookie, body: { text: 'First original', anchor: 'one', context: { label: 'One heading', quote: 'One' } } });
  assert.equal(first.status, 201);
  const initial = await request(a, '/tickets', { cookie });
  assert.equal(initial.status, 200);
  assert.equal(initial.json.tickets.length, 1);
  assert.ok(Number.isSafeInteger(initial.json.tickets[0].ref));
  assert.ok(initial.json.tickets[0].ref > 0);
  assert.equal(initial.json.tickets[0].mine, true);
  assert.deepEqual(initial.json.tickets[0].context, { label: 'One heading', quote: 'One' });
  assert.ok(initial.json.viewer.key);
  assert.equal(initial.json.viewer.verified, false);
  assert.equal(initial.json.tickets[0].changes[0].canEdit, true);
  const second = await request(a, '/tickets', { method: 'POST', token: a.write, body: { text: 'Second original' } });
  assert.equal(second.status, 201);
  const numbered = await request(a, '/tickets', { cookie });
  assert.equal(numbered.json.tickets.find(t => t.uuid === second.json.ticketUuid).ref, initial.json.tickets[0].ref + 1, 'reading and backfill do not consume new reference numbers');
  const page = await request(a, '/tickets?limit=1&sort=reference', { cookie });
  assert.ok(page.json.nextCursor);
  const rest = await request(a, `/tickets?limit=1&sort=reference&cursor=${encodeURIComponent(page.json.nextCursor)}`, { cookie });
  assert.equal(rest.status, 200);
  assert.equal(rest.json.tickets.length, 1);
  assert.notEqual(page.json.tickets[0].uuid, rest.json.tickets[0].uuid);
  const wrongQuery = await request(a, `/tickets?limit=1&q=changed&cursor=${encodeURIComponent(page.json.nextCursor)}`, { cookie });
  assert.equal(wrongQuery.status, 400);
  const matching = await request(a, '/tickets?q=original&filter=mine', { cookie });
  assert.equal(matching.json.tickets.length, 1);
  assert.equal(matching.json.tickets[0].ref, initial.json.tickets[0].ref);
});

test('only the proven message owner can correct text and history remains immutable', async () => {
  const a = await createArtifact(worker.base, worker.owner, '<h1>Corrections</h1>');
  const owner = await profile(a, 'Same name');
  const other = await profile(a, 'Same name');
  const posted = await request(a, '/tickets', { method: 'POST', cookie: owner, token: a.comment, body: { text: 'Original message' } });
  assert.equal(posted.status, 201);
  const { ticketUuid, artifact } = posted.json;
  const path = `/tickets/${ticketUuid}/messages/${artifact}`;
  const view = await request(a, '/tickets', { cookie: other, token: a.comment });
  assert.equal(view.json.tickets[0].changes[0].canEdit, false, 'a matching display name proves nothing');
  assert.equal((await request(a, path, { method: 'PATCH', token: a.comment, body: { text: 'No individual proof' } })).status, 404);
  assert.equal((await request(a, path, { method: 'PATCH', cookie: other, token: a.write, body: { text: 'Wrong person' } })).status, 404, 'write capability does not prove message ownership');
  assert.equal((await request(a, path, { method: 'PATCH', cookie: owner, token: a.comment, body: { text: 'Cannot change status', status: 'Closed' } })).status, 400);
  const corrected = await request(a, path, { method: 'PATCH', cookie: owner, token: a.read, body: { text: 'Corrected message' } });
  assert.equal(corrected.status, 200);
  assert.equal(corrected.json.correctionOf, artifact);
  assert.notEqual(corrected.json.artifact, artifact);
  const listing = await request(a, '/tickets?q=corrected', { cookie: owner });
  const ticket = listing.json.tickets[0];
  assert.equal(ticket.status, 'Open');
  assert.equal(ticket.changes.length, 1, 'a correction is not a second message');
  assert.equal(ticket.changes[0].artifact, artifact, 'original message identity is immutable');
  assert.equal(ticket.changes[0].text, 'Corrected message');
  assert.equal(ticket.changes[0].edited, true);
  assert.equal(ticket.changes[0].canEdit, true);
  assert.deepEqual(ticket.changes[0].history.map(h => h.text), ['Original message', 'Corrected message']);
  assert.equal(ticket.changes[0].history[0].artifact, artifact);
  assert.equal(ticket.changes[0].history[1].artifact, corrected.json.artifact);
  assert.equal((await request(a, `/tickets/${ticketUuid}/messages/${corrected.json.artifact}`, { method: 'PATCH', cookie: owner, body: { text: 'Cannot edit a correction artifact' } })).status, 404);
  const again = await request(a, path, { method: 'PATCH', cookie: owner, body: { text: 'Final message' } });
  assert.equal(again.status, 200);
  const current = await request(a, '/tickets', { cookie: owner });
  assert.deepEqual(current.json.tickets[0].changes[0].history.map(h => h.text), ['Original message', 'Corrected message', 'Final message']);
});

test('read markers and follows are private per real viewer and cannot mutate ticket state', async () => {
  const a = await createArtifact(worker.base, worker.owner, '<h1>Private view state</h1>');
  const reader = await profile(a, 'Reader');
  const other = await profile(a, 'Other reader');
  const opened = await request(a, '/tickets', { method: 'POST', token: a.write, body: { text: 'Please review' } });
  const { ticketUuid, artifact } = opened.json;
  const path = `/tickets/${ticketUuid}/view`;
  const before = await request(a, '/tickets?filter=unread', { cookie: reader });
  assert.equal(before.json.tickets.length, 1);
  assert.equal(before.json.tickets[0].unread, true);
  assert.equal(before.json.tickets[0].following, false);
  assert.equal((await request(a, path, { method: 'PUT', body: { following: true } })).status, 403);
  assert.equal((await request(a, path, { method: 'PUT', cookie: reader, body: { following: true, principal: 'other' } })).status, 400);
  assert.equal((await request(a, path, { method: 'PUT', cookie: reader, body: { readThrough: 'f'.repeat(64) } })).status, 404);
  const marked = await request(a, path, { method: 'PUT', cookie: reader, body: { readThrough: artifact, following: true } });
  assert.equal(marked.status, 200);
  const mine = await request(a, '/tickets', { cookie: reader });
  assert.equal(mine.json.tickets[0].unread, false);
  assert.equal(mine.json.tickets[0].following, true);
  const theirs = await request(a, '/tickets', { cookie: other });
  assert.equal(theirs.json.tickets[0].unread, true);
  assert.equal(theirs.json.tickets[0].following, false);
  assert.equal('readThrough' in theirs.json.tickets[0], false, 'private marker never appears on the public thread');
  assert.equal((await request(a, '/tickets', { method: 'POST', token: a.write, body: { ticketUuid, text: 'New activity' } })).status, 200);
  const activity = await request(a, '/tickets?filter=unread', { cookie: reader });
  assert.equal(activity.json.tickets.length, 1);
  assert.equal(activity.json.tickets[0].following, true);
  assert.equal((await request(a, path, { method: 'PUT', cookie: reader, body: { following: false } })).status, 200);
  const stillUnread = await request(a, '/tickets', { cookie: reader });
  assert.equal(stillUnread.json.tickets[0].unread, true, 'following preference does not mark messages read');
  assert.equal(stillUnread.json.tickets[0].following, false);
  assert.equal((await request(a, path, { method: 'PUT', cookie: reader, body: {} })).status, 200);
  const current = await request(a, '/tickets', { cookie: reader });
  assert.equal(current.json.tickets[0].unread, false);
  assert.equal(current.json.tickets[0].changes.length, 2, 'view writes never become Fossil ticket changes');
  assert.equal(current.json.tickets[0].status, 'Open');
});

test('account identity is independently verified, deliberate under capabilities and never upgrades role', async () => {
  const a = await createArtifact(worker.base, worker.owner, '<h1>Deliberate identity</h1>');
  const guest = await profile(a, 'Guest name');
  const session = await login('owner@example.com');
  const cookie = `${guest}; ${session}`;
  const defaults = await request(a, '/tickets', { cookie });
  assert.equal(defaults.json.viewer.verified, false, 'capability request stays guest by default');
  assert.ok(defaults.json.viewer.canUseAccount?.name);
  const account = await request(a, '/tickets?identity=account', { cookie });
  assert.equal(account.status, 200);
  assert.equal(account.json.viewer.verified, true);
  assert.notEqual(account.json.viewer.key, defaults.json.viewer.key);
  assert.equal((await request(a, '/tickets?identity=account')).status, 401, 'a capability alone is not a named account');
  const namedDefault = await request(a, '/tickets', { token: null, cookie: session });
  assert.equal(namedDefault.json.viewer.key, account.json.viewer.key, 'named cookie requests default to account');
  const guestPost = await request(a, '/tickets', { method: 'POST', cookie, body: { text: 'My guest message' } });
  assert.equal(guestPost.status, 201);
  const posted = await request(a, '/tickets', { method: 'POST', cookie: session, body: { text: 'My verified message', identity: 'account' } });
  assert.equal(posted.status, 201, 'a verified account does not need a guest profile');
  const current = await request(a, '/tickets?identity=account&filter=mine', { cookie });
  assert.equal(current.json.tickets.length, 1);
  assert.equal(current.json.tickets[0].uuid, posted.json.ticketUuid);
  assert.equal(current.json.tickets[0].changes[0].canEdit, true);
  assert.equal(current.json.tickets[0].changes[0].fields.authority, 'view', 'account display choice retains read authority');
  const exact = await request(a, `/tickets?thread=${posted.json.ticketUuid}&identity=account`, { cookie });
  assert.equal(exact.json.viewer.key, account.json.viewer.key, 'exact lookup uses the selected private principal');
  assert.equal(exact.json.tickets[0].changes[0].canEdit, true);
  const exactGuest = await request(a, `/tickets?thread=${posted.json.ticketUuid}`, { cookie });
  assert.equal(exactGuest.json.viewer.key, defaults.json.viewer.key);
  assert.equal(exactGuest.json.tickets[0].changes[0].canEdit, false);
  const editPath = `/tickets/${posted.json.ticketUuid}/messages/${posted.json.artifact}`;
  assert.equal((await request(a, editPath, { method: 'PATCH', cookie, body: { text: 'Wrong selected identity' } })).status, 404);
  assert.equal((await request(a, editPath, { method: 'PATCH', cookie, body: { text: 'Verified correction', identity: 'account' } })).status, 200);
  const close = await request(a, '/tickets', { method: 'POST', cookie, body: { ticketUuid: posted.json.ticketUuid, status: 'Closed', identity: 'account' } });
  assert.equal(close.status, 403, 'selecting the owner account cannot upgrade the read capability');
  const guestEdit = `/tickets/${guestPost.json.ticketUuid}/messages/${guestPost.json.artifact}`;
  assert.equal((await request(a, guestEdit, { method: 'PATCH', cookie, body: { text: 'Accounts cannot inherit guest ownership', identity: 'account' } })).status, 404);
  const guests = await request(a, '/tickets?filter=mine&identity=guest', { cookie });
  assert.equal(guests.json.tickets.length, 1);
  assert.equal(guests.json.tickets[0].uuid, guestPost.json.ticketUuid);
  const ownProfile = await request(a, '/guest', { cookie });
  const blocked = await fetch(`${worker.base}/api/artifacts/${a.id}/guests/${ownProfile.json.guest.id}`, { method: 'PATCH', headers: { Authorization: `Bearer ${worker.owner}` }, body: JSON.stringify({ blocked: true }) });
  assert.equal(blocked.status, 200);
  assert.equal((await request(a, '/tickets', { method: 'POST', cookie, body: { text: 'Cannot bypass block', identity: 'account' } })).status, 403);
  assert.equal((await request(a, '/tickets', { method: 'POST', cookie, body: { text: 'Default cannot bypass block' } })).status, 403);
  assert.equal((await request(a, editPath, { method: 'PATCH', cookie, body: { text: 'Blocked account correction', identity: 'account' } })).status, 404);
  const blockedList = await request(a, '/tickets?identity=account&filter=mine', { cookie });
  assert.equal(blockedList.json.tickets[0].changes[0].canEdit, false);
});
